/**
 * Virtual field: Post.readingTime
 *
 * Estimated reading time for a single post.
 */
export const readingTime: PostResolverModule["readingTime"] = (post) => {
  const wordCount = post.content.split(/\s+/).length;
  const minutes = Math.ceil(wordCount / WORDS_PER_MINUTE);
  return `${minutes} min read`;
};

/**
 * Virtual field: Post.excerpt
 *
 * Truncated content with ellipsis.
 */
export const excerpt: PostResolverModule["excerpt"] = (post, args) => {
  const length = args.length ?? 200;

  if (post.content.length <= length) {
    return post.content;
  }

  // Truncate at word boundary
  const truncated = post.content.slice(0, length);
  const lastSpace = truncated.lastIndexOf(" ");

  if (lastSpace > length * 0.8) {
    return truncated.slice(0, lastSpace) + "…";
  }

  return truncated + "…";
};

/**
 * Virtual field: Post.wordCount
 *
 * Simple word count.
 */
export const wordCount: PostResolverModule["wordCount"] = (post) => {
  return post.content.split(/\s+/).filter(Boolean).length;
};

