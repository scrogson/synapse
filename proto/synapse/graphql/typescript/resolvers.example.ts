const WORDS_PER_MINUTE = 200;

/**
 * Virtual field: Author.totalReadingTime
 *
 * Calculates estimated reading time for all posts by this author.
 */
export const totalReadingTime: AuthorResolverModule["totalReadingTime"] = async (
  author,
  _args,
  ctx
) => {
  const posts = await ctx.dataLoaders.postsByAuthor.load(author.id);

  const totalWords = posts.reduce((sum, post) => {
    return sum + post.content.split(/\s+/).length;
  }, 0);

  const minutes = Math.ceil(totalWords / WORDS_PER_MINUTE);

  if (minutes < 60) {
    return `${minutes} min read`;
  }

  const hours = Math.floor(minutes / 60);
  const remainingMinutes = minutes % 60;
  return `${hours}h ${remainingMinutes}m read`;
};

/**
 * Virtual field: Author.popularityScore
 *
 * Simple popularity score based on post count and published ratio.
 * In production, this might call an analytics service.
 */
export const popularityScore: AuthorResolverModule["popularityScore"] = async (
  author,
  _args,
  ctx
) => {
  const posts = await ctx.dataLoaders.postsByAuthor.load(author.id);

  if (posts.length === 0) return 0;

  const publishedCount = posts.filter((p) => p.published).length;
  const publishedRatio = publishedCount / posts.length;

  // Score: post count * published ratio * 10
  return Math.round(posts.length * publishedRatio * 10);
};

