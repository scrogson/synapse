import type { BlogServiceResolvers, Connection, Post } from "./generated";

/**
 * Custom RPC resolver: searchPosts
 *
 * Full-text search with pagination. In production, this would
 * call Elasticsearch, Meilisearch, or similar.
 */
export const searchPosts: BlogServiceResolvers["searchPosts"] = async (
  _parent,
  args,
  ctx
) => {
  const { query, first = 10, after } = args;

  // In production: call search service
  // For demo: simple in-memory filter (don't do this in production!)
  const allPosts: Post[] = []; // Would come from search index

  const filtered = allPosts.filter(
    (post) =>
      post.title.toLowerCase().includes(query.toLowerCase()) ||
      post.content.toLowerCase().includes(query.toLowerCase())
  );

  // Simple cursor pagination
  let startIndex = 0;
  if (after) {
    const afterIndex = filtered.findIndex((p) => encodeCursor(p.id) === after);
    startIndex = afterIndex + 1;
  }

  const slice = filtered.slice(startIndex, startIndex + first);
  const hasNextPage = startIndex + first < filtered.length;

  return {
    edges: slice.map((post) => ({
      cursor: encodeCursor(post.id),
      node: post,
    })),
    pageInfo: {
      hasNextPage,
      hasPreviousPage: startIndex > 0,
      startCursor: slice[0] ? encodeCursor(slice[0].id) : undefined,
      endCursor: slice[slice.length - 1]
        ? encodeCursor(slice[slice.length - 1].id)
        : undefined,
    },
    totalCount: filtered.length,
  };
};

// Helper for cursor encoding
function encodeCursor(id: number): string {
  return btoa(`Post:${id}`);
}
