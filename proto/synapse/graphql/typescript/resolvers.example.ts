/**
 * Virtual field: User.fullName
 *
 * Computes the user's display name. In this example, just returns
 * the name field, but could combine first/last name, handle i18n, etc.
 */
export const fullName: UserResolverModule["fullName"] = (user) => {
  return user.name;
};

/**
 * Virtual field: User.postCount
 *
 * Counts posts for this user. Uses DataLoader for efficient batching
 * when resolving multiple users in a single query.
 */
export const postCount: UserResolverModule["postCount"] = async (
  user,
  args,
  ctx
) => {
  // Get author profile for this user
  const author = await ctx.dataLoaders.authorByUserId.load(user.id);
  if (!author) return 0;

  // Get posts (uses DataLoader, batched across all users in query)
  const posts = await ctx.dataLoaders.postsByAuthor.load(author.id);

  // Filter by published status if specified
  if (args.published !== undefined) {
    return posts.filter((p) => p.published === args.published).length;
  }

  return posts.length;
};

/**
 * Field override: User.email -> maskEmail
 *
 * Masks the email domain for privacy in public APIs.
 * Only the authenticated user can see their full email.
 */
export const maskEmail: UserResolverModule["maskEmail"] = (user, _args, ctx) => {
  // Show full email to the user themselves
  if (ctx.currentUser?.id === user.id) {
    return user.email;
  }

  // Mask domain for other users
  const [local] = user.email.split("@");
  return `${local}@***`;
};

